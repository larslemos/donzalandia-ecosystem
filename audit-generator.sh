# Function to generate markdown header
generate_header() {
    local title=$1
    local level=$2
    if [ "$level" == "1" ]; then
        echo "# $title" >> "$AUDIT_DIR/FULL_AUDIT_REPORT.md"
        echo "" >> "$AUDIT_DIR/FULL_AUDIT_REPORT.md"
