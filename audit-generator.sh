        echo "## $title" >> "$AUDIT_DIR/FULL_AUDIT_REPORT.md"
        echo "" >> "$AUDIT_DIR/FULL_AUDIT_REPORT.md"
    elif [ "$level" == "3" ]; then
        echo "### $title" >> "$AUDIT_DIR/FULL_AUDIT_REPORT.md"
        echo "" >> "$AUDIT_DIR/FULL_AUDIT_REPORT.md"
